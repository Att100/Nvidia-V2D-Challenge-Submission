"""Run headless Codex reasoning and normalize its structured HOI output."""

from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import time
from pathlib import Path
from typing import Any

import cv2
import numpy as np

from pipeline.utils import parse_worker_args


_EXCLUDED_SUPPORT_NAME_PATTERNS = (
    re.compile(r"\btable\b", re.IGNORECASE),
    re.compile(r"\bdesk\b", re.IGNORECASE),
    re.compile(r"\bwork\s*top\b", re.IGNORECASE),
    re.compile(r"\bcounter(?:top)?\b", re.IGNORECASE),
)


def _excluded_support_reason(name: str, prompt: str) -> str | None:
    """Reject large planar furniture that is not reconstructible from one view."""

    text = f"{name} {prompt}"
    if any(pattern.search(text) for pattern in _EXCLUDED_SUPPORT_NAME_PATTERNS):
        return "large_planar_furniture"
    return None


def parse_args() -> argparse.Namespace:
    """Parse the worker job generated by the pipeline orchestrator."""

    parser = argparse.ArgumentParser()
    parser.add_argument("--video", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--repository-root", type=Path, required=True)
    parser.add_argument("--codex-binary", default="codex")
    parser.add_argument("--model", default="gpt-6-astra")
    parser.add_argument("--reasoning-effort", default="high")
    parser.add_argument("--output-schema", type=Path, required=True)
    parser.add_argument("--prompt-template", required=True)
    parser.add_argument("--timeout-seconds", type=int, default=3600)
    parser.add_argument("--schema-version", required=True)
    return parse_worker_args(parser)


def video_metadata(path: Path) -> tuple[int, float, int, int]:
    """Return authoritative OpenCV frame count, FPS, width, and height."""

    capture = cv2.VideoCapture(str(path))
    if not capture.isOpened():
        raise OSError(f"Cannot open video: {path}")
    try:
        count = int(capture.get(cv2.CAP_PROP_FRAME_COUNT))
        fps = float(capture.get(cv2.CAP_PROP_FPS))
        width = int(capture.get(cv2.CAP_PROP_FRAME_WIDTH))
        height = int(capture.get(cv2.CAP_PROP_FRAME_HEIGHT))
    finally:
        capture.release()
    if min(count, fps, width, height) <= 0:
        raise ValueError(f"Invalid video metadata for {path}")
    return count, fps, width, height


def _validate_bbox(value: Any, width: int, height: int, label: str) -> list[int]:
    """Validate an original-resolution, half-open xyxy bounding box."""

    if not isinstance(value, list) or len(value) != 4:
        raise ValueError(f"{label} must be a four-element bbox")
    box = [int(item) for item in value]
    x0, y0, x1, y1 = box
    if not (0 <= x0 < x1 <= width and 0 <= y0 < y1 <= height):
        raise ValueError(f"{label} is outside {width}x{height}: {box}")
    return box


def validate_and_normalize(
    raw: dict[str, Any],
    *,
    video: Path,
    frame_count: int,
    fps: float,
    width: int,
    height: int,
    schema_version: str,
) -> dict[str, Any]:
    """Check cross-field invariants and add deterministic timing/event views."""

    objects = raw.get("objects")
    support_objects = raw.get("support_objects")
    hands = raw.get("hands")
    interactions = raw.get("interactions")
    if (
        not isinstance(objects, list)
        or not isinstance(support_objects, list)
        or not isinstance(hands, list)
        or not isinstance(interactions, list)
    ):
        raise TypeError(
            "Codex output must contain objects, support_objects, hands, and "
            "interactions arrays"
        )
    if int(raw.get("num_interactions", -1)) != len(interactions):
        raise ValueError("num_interactions does not match interactions length")
    if [int(item["id"]) for item in objects] != list(range(len(objects))):
        raise ValueError("Object IDs must be contiguous and zero based")
    if [int(item["id"]) for item in support_objects] != list(
        range(len(support_objects))
    ):
        raise ValueError("Support-object IDs must be contiguous and zero based")
    if [int(item["id"]) for item in interactions] != list(range(len(interactions))):
        raise ValueError("Interaction IDs must be contiguous and zero based")

    normalized_objects: list[dict[str, Any]] = []
    for item in objects:
        object_id = int(item["id"])
        canonical = item["canonical"]
        frame = int(canonical["frame"])
        if not 0 <= frame < frame_count:
            raise ValueError(f"Object {object_id} canonical frame is outside the video")
        bbox = _validate_bbox(
            canonical["bbox_xyxy"], width, height, f"object {object_id} canonical"
        )
        normalized_objects.append(
            {
                "id": object_id,
                "global_object_id": f"object_{object_id:03d}",
                "name": str(item["name"]).strip(),
                "sam3_prompt": str(item["sam3_prompt"]).strip(),
                "canonical": {
                    "frame": frame,
                    "time_sec": frame / fps,
                    "bbox_xyxy": bbox,
                },
            }
        )
    if any(not item["name"] or not item["sam3_prompt"] for item in normalized_objects):
        raise ValueError("Object names and SAM3 prompts must be non-empty")

    normalized_supports: list[dict[str, Any]] = []
    excluded_supports: list[dict[str, Any]] = []
    for item in support_objects:
        raw_support_id = int(item["id"])
        canonical = item["canonical"]
        frame = int(canonical["frame"])
        if not 0 <= frame < frame_count:
            raise ValueError(
                f"Support object {raw_support_id} canonical frame is outside the video"
            )
        bbox = _validate_bbox(
            canonical["bbox_xyxy"],
            width,
            height,
            f"support object {raw_support_id} canonical",
        )
        name = str(item["name"]).strip()
        sam3_prompt = str(item["sam3_prompt"]).strip()
        excluded_reason = _excluded_support_reason(name, sam3_prompt)
        if excluded_reason is not None:
            excluded_supports.append(
                {
                    "raw_id": raw_support_id,
                    "name": name,
                    "sam3_prompt": sam3_prompt,
                    "reason": excluded_reason,
                }
            )
            continue
        # Filtering happens after strict raw-schema validation. Reindex the retained
        # registry so downstream support paths remain contiguous and deterministic.
        support_id = len(normalized_supports)
        global_id = f"support_{support_id:03d}"
        normalized_supports.append(
            {
                "id": support_id,
                "global_object_id": global_id,
                "global_support_id": global_id,
                "name": name,
                "sam3_prompt": sam3_prompt,
                "canonical": {
                    "frame": frame,
                    "time_sec": frame / fps,
                    "bbox_xyxy": bbox,
                },
            }
        )
    if any(not item["name"] or not item["sam3_prompt"] for item in normalized_supports):
        raise ValueError("Support-object names and SAM3 prompts must be non-empty")

    if len(hands) != 2:
        raise ValueError("Codex output must contain exactly two wearer-hand records")
    by_side: dict[str, dict[str, Any]] = {}
    for item in hands:
        side = str(item["side"])
        if side not in {"left", "right"} or side in by_side:
            raise ValueError("Hand records must contain one unique left and right side")
        by_side[side] = item
    if set(by_side) != {"left", "right"}:
        raise ValueError("Hand records must contain both anatomical sides")

    normalized_hands: list[dict[str, Any]] = []
    for side in ("left", "right"):
        observations: list[dict[str, Any]] = []
        seen_frames: set[int] = set()
        for canonical_index, canonical in enumerate(by_side[side]["canonicals"]):
            frame = int(canonical["frame"])
            if not 0 <= frame < frame_count:
                raise ValueError(
                    f"{side} hand canonical {canonical_index} is outside the video"
                )
            if frame in seen_frames:
                raise ValueError(f"{side} hand repeats canonical frame {frame}")
            seen_frames.add(frame)
            bbox = _validate_bbox(
                canonical["bbox_xyxy"],
                width,
                height,
                f"{side} hand canonical {canonical_index}",
            )
            observations.append(
                {
                    "id": canonical_index,
                    "frame": frame,
                    "time_sec": frame / fps,
                    "bbox_xyxy": bbox,
                }
            )
        observations.sort(key=lambda item: item["frame"])
        for canonical_index, observation in enumerate(observations):
            observation["id"] = canonical_index
        normalized_hands.append(
            {
                "side": side,
                "global_hand_id": f"hand_{side}",
                "sam3_prompt": "hand",
                "canonicals": observations,
            }
        )

    normalized_interactions: list[dict[str, Any]] = []
    events: list[dict[str, Any]] = []
    for item in interactions:
        interaction_id = int(item["id"])
        object_index = int(item["object"])
        if not 0 <= object_index < len(normalized_objects):
            raise ValueError(f"Interaction {interaction_id} references an unknown object")
        start, end = (int(value) for value in item["frame_interval"])
        if not 0 <= start <= end < frame_count:
            raise ValueError(f"Interaction {interaction_id} has invalid frame interval")
        hand = str(item["hand"])
        object_record = normalized_objects[object_index]
        atom = {
            "hand": hand,
            "start_frame": start,
            "end_frame": end,
            "start_time_sec": start / fps,
            "end_time_sec": end / fps,
            "action": "interact",
            "physical_support": "unknown",
        }
        normalized_interactions.append(
            {
                "id": interaction_id,
                "hand": hand,
                "object": object_index,
                "global_object_id": object_record["global_object_id"],
                "frame_interval": [start, end],
                "time_interval_sec": [start / fps, end / fps],
            }
        )
        events.append(
            {
                "event_id": f"interaction_{interaction_id:04d}",
                "object_id": object_index,
                "global_object_id": object_record["global_object_id"],
                "object": object_record["name"],
                "prompts": [object_record["sam3_prompt"]],
                "start_frame": start,
                "end_frame": end,
                "start_time_sec": start / fps,
                "end_time_sec": end / fps,
                "atoms": [atom],
                "confidence": 1.0,
            }
        )
    return {
        "schema_version": schema_version,
        "reasoner": "codex_exec",
        "video": {
            "path": str(video),
            "num_frames": frame_count,
            "fps": fps,
            "width": width,
            "height": height,
        },
        "num_interactions": len(normalized_interactions),
        "objects": normalized_objects,
        "support_objects": normalized_supports,
        "excluded_support_objects": excluded_supports,
        "hands": normalized_hands,
        "interactions": normalized_interactions,
        "events": events,
    }


def read_frame(capture: cv2.VideoCapture, frame_id: int) -> np.ndarray:
    """Read one exact native video frame."""

    capture.set(cv2.CAP_PROP_POS_FRAMES, frame_id)
    ok, frame = capture.read()
    if not ok:
        raise OSError(f"Cannot read frame {frame_id}")
    return frame


def write_visualizations(video: Path, result: dict[str, Any], output: Path) -> dict[str, str]:
    """Render every object, support, and wearer-hand canonical observation."""

    frame_dir = output / "canonical_frames"
    frame_dir.mkdir(parents=True, exist_ok=True)
    capture = cv2.VideoCapture(str(video))
    cards: list[np.ndarray] = []
    try:
        records = [
            *(dict(item, registry="object") for item in result["objects"]),
            *(dict(item, registry="support") for item in result["support_objects"]),
        ]
        for hand in result["hands"]:
            for canonical in hand["canonicals"]:
                records.append(
                    {
                        "registry": "hand",
                        "global_object_id": (
                            f"{hand['global_hand_id']}_{int(canonical['id']):02d}"
                        ),
                        "name": f"wearer {hand['side']} hand",
                        "canonical": canonical,
                    }
                )
        for item in records:
            frame_id = int(item["canonical"]["frame"])
            x0, y0, x1, y1 = item["canonical"]["bbox_xyxy"]
            frame = read_frame(capture, frame_id)
            colour = (255, 180, 30) if item["registry"] == "hand" else (40, 230, 80)
            cv2.rectangle(frame, (x0, y0), (x1, y1), colour, 5)
            label = f"{item['global_object_id']} {item['name']} frame={frame_id}"
            cv2.putText(
                frame,
                label,
                (max(4, x0), max(30, y0 - 10)),
                cv2.FONT_HERSHEY_SIMPLEX,
                0.8,
                colour,
                2,
                cv2.LINE_AA,
            )
            target = frame_dir / f"{item['global_object_id']}_frame_{frame_id:06d}.jpg"
            if not cv2.imwrite(str(target), frame):
                raise OSError(target)
            scale = min(640 / frame.shape[1], 420 / frame.shape[0])
            card = cv2.resize(frame, (round(frame.shape[1] * scale), round(frame.shape[0] * scale)))
            canvas = np.zeros((440, 660, 3), dtype=np.uint8)
            top = (420 - card.shape[0]) // 2
            left = (660 - card.shape[1]) // 2
            canvas[top : top + card.shape[0], left : left + card.shape[1]] = card
            cards.append(canvas)
    finally:
        capture.release()
    montage_path = output / "canonical_bboxes.jpg"
    if cards:
        columns = 2
        rows = (len(cards) + columns - 1) // columns
        while len(cards) < rows * columns:
            cards.append(np.zeros_like(cards[0]))
        montage = np.vstack(
            [np.hstack(cards[row * columns : (row + 1) * columns]) for row in range(rows)]
        )
        if not cv2.imwrite(str(montage_path), montage):
            raise OSError(montage_path)
    else:
        montage_path.write_bytes(b"")
    return {
        "canonical_frames_dir": str(frame_dir.resolve()),
        "canonical_bboxes_montage": str(montage_path.resolve()),
        "object_canonical_bboxes_montage": str(montage_path.resolve()),
        "hand_canonical_bboxes_montage": str(montage_path.resolve()),
    }


def run_reasoning(args: argparse.Namespace) -> None:
    """Invoke Codex once, validate strict JSON, and emit pipeline-ready semantics."""

    video = args.video.expanduser().resolve()
    output = args.output_dir.expanduser().resolve()
    repository = args.repository_root.expanduser().resolve()
    schema = args.output_schema.expanduser().resolve()
    output.mkdir(parents=True, exist_ok=True)
    audit_dir = output / "codex_workspace"
    audit_dir.mkdir(parents=True, exist_ok=True)
    frame_count, fps, width, height = video_metadata(video)
    prompt = (
        args.prompt_template.replace("{video_path}", str(video))
        .replace("{output_dir}", str(audit_dir))
        .replace("{num_frames}", str(frame_count))
        .replace("{fps}", f"{fps:.9g}")
        .replace("{width}", str(width))
        .replace("{height}", str(height))
    )
    prompt_path = output / "prompt.txt"
    prompt_path.write_text(prompt, encoding="utf-8")
    answer_path = output / "codex_raw_response.json"
    stdout_path = output / "codex_stdout.jsonl"
    stderr_path = output / "codex_stderr.log"
    binary = shutil.which(args.codex_binary) or args.codex_binary
    command = [
        binary,
        "exec",
        "--model",
        args.model,
        "--sandbox",
        "workspace-write",
        "--cd",
        str(repository),
        "--skip-git-repo-check",
        "--ephemeral",
        "--json",
        "--config",
        f'model_reasoning_effort="{args.reasoning_effort}"',
        "--config",
        'approval_policy="never"',
        "--output-schema",
        str(schema),
        "--output-last-message",
        str(answer_path),
        "-",
    ]
    started = time.perf_counter()
    completed = subprocess.run(
        command,
        input=prompt,
        text=True,
        capture_output=True,
        timeout=args.timeout_seconds,
        check=False,
        cwd=repository,
    )
    stdout_path.write_text(completed.stdout, encoding="utf-8")
    stderr_path.write_text(completed.stderr, encoding="utf-8")
    if completed.returncode != 0:
        raise RuntimeError(
            f"codex exec exited with {completed.returncode}; see {stderr_path}"
        )
    raw = json.loads(answer_path.read_text(encoding="utf-8"))
    normalized = validate_and_normalize(
        raw,
        video=video,
        frame_count=frame_count,
        fps=fps,
        width=width,
        height=height,
        schema_version=args.schema_version,
    )
    normalized["artifacts"] = write_visualizations(video, normalized, output)
    result_path = output / "contact_events.json"
    result_path.write_text(
        json.dumps(normalized, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    report = {
        "schema_version": "codex-hoi-reasoning-report-v2",
        "model": args.model,
        "reasoning_effort": args.reasoning_effort,
        "elapsed_seconds": time.perf_counter() - started,
        "video": str(video),
        "objects": len(normalized["objects"]),
        "support_objects": len(normalized["support_objects"]),
        "hand_canonical_counts": {
            item["side"]: len(item["canonicals"]) for item in normalized["hands"]
        },
        "interactions": len(normalized["interactions"]),
        "prompt": str(prompt_path),
        "raw_response": str(answer_path),
        "stdout_events": str(stdout_path),
        "stderr": str(stderr_path),
    }
    (output / "report.json").write_text(
        json.dumps(report, indent=2) + "\n", encoding="utf-8"
    )
    print(result_path)


class CodexHOIReasoner:
    """Worker-facing headless Codex whole-video reasoner."""

    def __init__(self, arguments: argparse.Namespace) -> None:
        self.arguments = arguments

    @classmethod
    def from_worker_job(cls) -> "CodexHOIReasoner":
        return cls(parse_args())

    def run(self) -> None:
        run_reasoning(self.arguments)


def main() -> None:
    CodexHOIReasoner.from_worker_job().run()


if __name__ == "__main__":
    main()
