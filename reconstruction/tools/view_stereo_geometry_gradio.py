def _load_viewer_backend(path: Path):
    """Load the vendored persistent WebGL component from this repository."""
    resolved = path.expanduser().resolve()
    if not resolved.is_file():
        raise FileNotFoundError(
            "Vendored WebGL viewer not found. Pass --viewer-backend or restore: "
            f"{resolved}"
        )
    module_name = "ego_scene_hoi_stereo_gradio_backend"
    spec = importlib.util.spec_from_file_location(module_name, resolved)
    if spec is None or spec.loader is None:
        raise ImportError(f"Could not load viewer backend: {resolved}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[module_name] = module
    spec.loader.exec_module(module)
    return module


def _backend_path_from_process() -> Path:
    parser = argparse.ArgumentParser(add_help=False)
    parser.add_argument("--viewer-backend", type=Path)
    args, _ = parser.parse_known_args()
    return Path(
        args.viewer_backend
        or os.environ.get("TRACK3_GRADIO_BACKEND", str(DEFAULT_BACKEND))
    )


viewer = _load_viewer_backend(_backend_path_from_process())


def _configure_stereo_webgl_backend(module: Any) -> None:
    """Add viewer-local point-size control and a closer zoom limit.

    The vendored backend is loaded as a private module instance, so changing
    its JavaScript string here affects only this application.
    """
    javascript = module.POINTCLOUD_JS
    replacements = (
        (
            "const dynamicCloud = makeCloud();",
            "const dynamicCloud = makeCloud();\nlet dynamicPointSize = 3.0;",
        ),
        (
            "const payload = JSON.parse(raw);",
            "const payload = JSON.parse(raw);\n"
            "    if (Number.isFinite(Number(payload.point_size))) {\n"
            "      dynamicPointSize = Math.max(0.25, Math.min(20.0, Number(payload.point_size)));\n"
            "    }",
        ),
        ("bindCloud(dynamicCloud, 3.0);", "bindCloud(dynamicCloud, dynamicPointSize);"),
        (
            "distance = Math.max(1.15, Math.min(30.0, distance * Math.exp(event.deltaY * 0.001)));",
            "distance = Math.max(0.05, Math.min(30.0, distance * Math.exp(event.deltaY * 0.001)));",
        ),
        (
            "seekSynchronizedVideo('#source-video-player', payload.source_video_position);",
            "seekSynchronizedVideo('#source-video-player', payload.source_video_position);\n"
            "    seekSynchronizedVideo('#right-video-player', payload.source_video_position);",
        ),
    )
    for old, new in replacements:
        if old not in javascript:
            raise RuntimeError(f"Vendored WebGL backend changed; patch target not found: {old}")
        javascript = javascript.replace(old, new, 1)
    module.POINTCLOUD_JS = javascript


