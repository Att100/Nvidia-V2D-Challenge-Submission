@dataclass(frozen=True)
class PackedMaskSequence:
    """One bit-packed mask sequence plus its source-frame mapping."""

    packed: np.ndarray
    width: int
    source_indices: np.ndarray

    def frame(self, frame_id: int, height: int) -> np.ndarray:
        matches = np.flatnonzero(self.source_indices == frame_id)
        if not len(matches):
            return np.zeros((height, self.width), dtype=bool)
        row = self.packed[int(matches[0])]
        return np.unpackbits(row, axis=1, count=self.width).astype(bool, copy=False)


class VideoFrameReader:
    """Thread-safe seekable OpenCV reader with a small RGB frame cache."""

    def __init__(self, path: Path, cache_size: int = 16) -> None:
        self.path = path
        self.capture = cv2.VideoCapture(str(path))
        if not self.capture.isOpened():
            raise RuntimeError(f"Could not open video: {path}")
        self.frame_count = int(round(self.capture.get(cv2.CAP_PROP_FRAME_COUNT)))
        self.width = int(round(self.capture.get(cv2.CAP_PROP_FRAME_WIDTH)))
        self.height = int(round(self.capture.get(cv2.CAP_PROP_FRAME_HEIGHT)))
        self.fps = float(self.capture.get(cv2.CAP_PROP_FPS))
        self.cache_size = cache_size
        self.cache: OrderedDict[int, np.ndarray] = OrderedDict()
        self.lock = threading.Lock()
        self.next_decode_frame = 0

    def read(self, frame_id: int) -> np.ndarray:
        """Return one RGB uint8 frame."""
        frame_id = int(np.clip(frame_id, 0, max(0, self.frame_count - 1)))
        with self.lock:
            cached = self.cache.pop(frame_id, None)
            if cached is not None:
                self.cache[frame_id] = cached
                return cached.copy()
            if frame_id != self.next_decode_frame:
                self.capture.set(cv2.CAP_PROP_POS_FRAMES, frame_id)
            ok, frame = self.capture.read()
            if not ok or frame is None:
                raise RuntimeError(f"Failed to decode frame {frame_id} from {self.path}")
            rgb = cv2.cvtColor(frame, cv2.COLOR_BGR2RGB)
            self.next_decode_frame = frame_id + 1
            self.cache[frame_id] = rgb
            while len(self.cache) > self.cache_size:
                self.cache.popitem(last=False)
            return rgb.copy()

    def close(self) -> None:
        with self.lock:
            self.capture.release()
            self.cache.clear()


class StereoRun:
    """Lazy, bounded-memory access to one stereo geometry experiment."""

    def __init__(self, artifacts: StereoArtifacts) -> None:
        self.artifacts = artifacts
        browser_media_dir = artifacts.root / "visualization/gradio_media"
        self.left_browser_video = viewer._prepare_browser_video(
            artifacts.left_video, browser_media_dir, "rectified_left"
        )
        self.right_browser_video = viewer._prepare_browser_video(
            artifacts.right_video, browser_media_dir, "rectified_right"
        )
        self.left_reader = VideoFrameReader(artifacts.left_video)
        self.right_reader = VideoFrameReader(artifacts.right_video)
        if (self.left_reader.width, self.left_reader.height) != (
            self.right_reader.width,
            self.right_reader.height,
        ):
            raise ValueError("Rectified stereo videos have different resolutions")

        calibration = np.load(artifacts.calibration, allow_pickle=False)
        self.K = np.asarray(
            calibration["K_working"] if "K_working" in calibration else calibration["K"],
            dtype=np.float64,
        )
        self.baseline_m = float(calibration["baseline_m"])
        self.left_valid = np.asarray(
            calibration.get(
                "left_valid",
                np.ones((self.left_reader.height, self.left_reader.width), dtype=bool),
            ),
            dtype=bool,
        )
        self.right_valid = np.asarray(
            calibration.get(
                "right_valid",
                np.ones((self.right_reader.height, self.right_reader.width), dtype=bool),
            ),
            dtype=bool,
        )
        self.left_masks = self._load_masks(artifacts.left_mask_archive)
        self.right_masks = (
            self._load_masks(artifacts.right_mask_archive)
            if artifacts.right_mask_archive is not None
            else None
        )

        pose_data = np.load(artifacts.pose_archive, allow_pickle=False)
        poses = np.asarray(pose_data["data"], dtype=np.float64)
        pose_indices = np.asarray(
            pose_data["inds"] if "inds" in pose_data else np.arange(len(poses)),
            dtype=np.int64,
        )
        self.pose_by_frame = {int(index): pose for index, pose in zip(pose_indices, poses)}

        self.hand_track = (
            self._load_hand_motion(artifacts.hand_motion)
            if artifacts.hand_motion is not None
            else None
        )

        self.object_tracks: list[ObjectTrack] = []
        for object_artifact in artifacts.objects:
            pose_sources = dict(object_artifact.pose_archives)
            poses_by_source = {
                source: self._load_object_pose_sequence(path)
                for source, path in object_artifact.pose_archives
            }
            mesh = viewer._load_single_mesh(object_artifact.mesh)
            bbox_to_origin, bbox_extents = viewer.trimesh.bounds.oriented_bounds(mesh)
            self.object_tracks.append(
                ObjectTrack(
                    object_id=object_artifact.object_id,
                    label=object_artifact.label,
                    pose_sources=pose_sources,
                    mesh_source=object_artifact.mesh,
                    poses_by_source=poses_by_source,
                    mesh_payload=viewer.encode_textured_mesh(mesh),
                    bbox_to_mesh=np.linalg.inv(bbox_to_origin),
                    bbox_extents=np.asarray(bbox_extents, dtype=np.float64),
                )
            )

        left_depth_count = len(list(artifacts.left_depth_dir.glob("*.npy")))
        candidate_counts = [
            self.left_reader.frame_count,
            self.right_reader.frame_count,
            left_depth_count,
        ]
        if len(self.left_masks.source_indices):
            candidate_counts.append(int(self.left_masks.source_indices.max()) + 1)
        self.frame_count = min(candidate_counts)
        self.center, self.scale, self.extent = self._estimate_world_normalization()
        self.depth_cache: OrderedDict[tuple[str, int], np.ndarray] = OrderedDict()
        self.depth_cache_size = 8
        self.cloud_cache: OrderedDict[tuple[int, int, float, bool, int], tuple[dict[str, Any], int]] = OrderedDict()
        self.cloud_cache_size = 12

    @staticmethod
    def _load_object_pose_sequence(path: Path) -> dict[int, np.ndarray]:
        """Decode either FoundationPose/surface or optimizer pose archives."""

        with np.load(path, allow_pickle=False) as archive:
            if "ob_in_world" in archive:
                poses = np.asarray(archive["ob_in_world"], dtype=np.float64)
            elif "object_to_world" in archive:
                poses = np.asarray(archive["object_to_world"], dtype=np.float64)
            else:
                raise ValueError(
                    "Object pose archive lacks ob_in_world/object_to_world: "
                    f"{path}"
                )
            indices = np.asarray(
                archive["source_indices"]
                if "source_indices" in archive
                else np.arange(len(poses)),
                dtype=np.int64,
            )
            valid = np.asarray(
                archive["valid"]
                if "valid" in archive
                else np.isfinite(poses).all(axis=(1, 2)),
                dtype=bool,
            )
        if len(indices) != len(poses) or len(valid) != len(poses):
            raise ValueError(f"Object pose array lengths do not match: {path}")
        valid &= np.isfinite(poses).all(axis=(1, 2))
        return {
            int(index): pose
            for index, pose, keep in zip(indices, poses, valid, strict=True)
            if keep
        }

    @property
    def available_pose_sources(self) -> list[str]:
        """Return pose sources available for every loaded object, in stage order."""

        if not self.object_tracks:
            return [FOUNDATIONPOSE_SOURCE]
        common = set(self.object_tracks[0].poses_by_source)
        for track in self.object_tracks[1:]:
            common.intersection_update(track.poses_by_source)
        choices = [source for source in POSE_SOURCE_ORDER if source in common]
        if choices:
            return choices
        union = set().union(*(track.poses_by_source for track in self.object_tracks))
        return [source for source in POSE_SOURCE_ORDER if source in union]

    @staticmethod
    def _load_hand_motion(path: Path) -> HandMotionTrack:
        """Load only the final MANO geometry required by the interactive viewer."""
        with np.load(path, allow_pickle=False) as archive:
            required = {"vertices_world", "valid", "faces_left", "faces_right"}
            missing = required.difference(archive.files)
            if missing:
                raise ValueError(
                    f"Hand-motion archive is missing keys {sorted(missing)}: {path}"
                )
            vertices = np.asarray(archive["vertices_world"], dtype=np.float32)
            valid = np.asarray(archive["valid"], dtype=bool)
            faces = (
                np.asarray(archive["faces_left"], dtype=np.int32),
                np.asarray(archive["faces_right"], dtype=np.int32),
            )
            source_indices = np.asarray(
                archive["source_indices"]
                if "source_indices" in archive
                else np.arange(len(vertices)),
                dtype=np.int64,
            )
            raw_labels = (
                [str(item) for item in archive["hand_labels"].tolist()]
                if "hand_labels" in archive
                else ["left", "right"]
            )
        if vertices.ndim != 4 or vertices.shape[1] != 2 or vertices.shape[-1] != 3:
            raise ValueError(f"Hand vertices must have shape Fx2xVx3: {vertices.shape}")
        if valid.shape != vertices.shape[:2]:
            raise ValueError(
                f"Hand validity shape {valid.shape} does not match {vertices.shape[:2]}"
            )
        if len(source_indices) != len(vertices):
            raise ValueError("Hand source_indices do not match the geometry sequence")
        for hand_faces in faces:
            if hand_faces.ndim != 2 or hand_faces.shape[1] != 3:
                raise ValueError(f"Hand faces must have shape Tx3: {hand_faces.shape}")
        labels = tuple((raw_labels + ["left", "right"])[:2])
        colors = np.asarray(
            getattr(viewer, "HAND_COLORS", [[255, 176, 72], [86, 232, 133]]),
            dtype=np.uint8,
        )
        return HandMotionTrack(
            source=path,
            vertices_world=vertices,
            valid=valid,
            faces=faces,
            labels=(str(labels[0]), str(labels[1])),
            source_to_row={int(frame_id): row for row, frame_id in enumerate(source_indices)},
            textures=tuple(viewer._solid_texture_data_url(color) for color in colors[:2]),
            texcoords=tuple(
                base64.b64encode(
                    np.zeros((len(hand_faces) * 3, 2), dtype="<f4").tobytes()
                ).decode("ascii")
                for hand_faces in faces
            ),
            mesh_cache=OrderedDict(),
        )

    def hand_meshes(
        self,
        frame_id: int,
        *,
        visible: bool,
        opacity: float,
    ) -> tuple[list[dict[str, Any]], list[str]]:
        """Encode the valid left/right MANO meshes in the normalized world frame."""
        track = self.hand_track
        if track is None:
            return [], []
        normalization = np.eye(4, dtype=np.float64)
        normalization[:3, :3] *= float(self.scale)
        normalization[:3, 3] = -self.center.astype(np.float64) * float(self.scale)
        model = normalization.astype(np.float32).reshape(-1, order="F").tolist()
        row = track.source_to_row.get(int(frame_id))
        payloads: list[dict[str, Any]] = []
        visible_labels: list[str] = []
        for hand_id in range(2):
            active = bool(
                visible
                and row is not None
                and track.valid[row, hand_id]
                and np.isfinite(track.vertices_world[row, hand_id]).all()
            )
            payload: dict[str, Any] = {
                "visible": active,
                "model": model,
                "opacity": float(np.clip(opacity, 0.05, 1.0)),
            }
            if active:
                cache_key = (row, hand_id)
                geometry = track.mesh_cache.pop(cache_key, None)
                if geometry is None:
                    vertices = np.asarray(
                        track.vertices_world[row, hand_id], dtype=np.float32
                    )
                    faces = np.asarray(track.faces[hand_id], dtype=np.int64)
                    triangles = np.ascontiguousarray(
                        vertices[faces].reshape(-1, 3), dtype="<f4"
                    )
                    normals = viewer.expanded_smooth_mesh_normals(vertices, faces)
                    geometry = {
                        "count": len(triangles),
                        "triangle_count": len(faces),
                        "positions": base64.b64encode(triangles.tobytes()).decode("ascii"),
                        "normals": base64.b64encode(normals.tobytes()).decode("ascii"),
                        "texcoords": track.texcoords[hand_id],
                        "texture": track.textures[hand_id],
                        "lighting_strength": 1.0,
                    }
                    track.mesh_cache[cache_key] = geometry
                    while len(track.mesh_cache) > 48:
                        track.mesh_cache.popitem(last=False)
                else:
                    track.mesh_cache[cache_key] = geometry
                payload.update(geometry)
                visible_labels.append(track.labels[hand_id])
            payloads.append(payload)
        return payloads, visible_labels

    @staticmethod
    def _load_masks(path: Path) -> PackedMaskSequence:
        archive = np.load(path, allow_pickle=False)
        packed = np.asarray(archive["packed_masks"], dtype=np.uint8)
        width = int(archive["mask_width"])
        source_indices = np.asarray(
            archive["source_indices"]
            if "source_indices" in archive
            else np.arange(len(packed)),
            dtype=np.int64,
        )
        return PackedMaskSequence(packed, width, source_indices)

    def close(self) -> None:
        self.left_reader.close()
        self.right_reader.close()

    def pose(self, frame_id: int) -> np.ndarray:
        pose = self.pose_by_frame.get(frame_id)
        if pose is not None:
            return pose
        keys = np.asarray(list(self.pose_by_frame), dtype=np.int64)
        if not len(keys):
            return np.eye(4, dtype=np.float64)
        return self.pose_by_frame[int(keys[np.argmin(np.abs(keys - frame_id))])]

    @staticmethod
    def object_pose(
        track: ObjectTrack, frame_id: int, pose_source: str
    ) -> np.ndarray | None:
        """Return the selected stage pose with an explicit upstream fallback chain."""

        fallback = POSE_SOURCE_FALLBACKS.get(
            pose_source, (pose_source, FOUNDATIONPOSE_SOURCE)
        )
        for source in fallback:
            pose = track.poses_by_source.get(source, {}).get(int(frame_id))
            if pose is not None:
                return pose
        return None

    def object_meshes(
        self,
        frame_id: int,
        *,
        visible: bool,
        include_geometry: bool,
        opacity: float,
        pose_source: str,
    ) -> list[dict[str, Any]]:
        """Build the textured-mesh payload in the normalized WebGL world."""
        payloads: list[dict[str, Any]] = []
        normalization = np.eye(4, dtype=np.float64)
        normalization[:3, :3] *= float(self.scale)
        normalization[:3, 3] = -self.center.astype(np.float64) * float(self.scale)
        for track in self.object_tracks:
            pose = self.object_pose(track, frame_id, pose_source)
            payload: dict[str, Any] = {
                "visible": bool(visible and pose is not None),
                "model": np.eye(4, dtype=np.float32).reshape(-1, order="F").tolist(),
                "opacity": float(np.clip(opacity, 0.05, 1.0)),
            }
            if pose is not None:
                model = normalization @ pose
                payload["model"] = model.astype(np.float32).reshape(-1, order="F").tolist()
            if include_geometry:
                payload.update(track.mesh_payload)
                payload["opacity"] = float(np.clip(opacity, 0.05, 1.0))
            payloads.append(payload)
        return payloads

    def encoded_point_cloud(
        self,
        frame_id: int,
        pixel_stride: int,
        max_depth: float,
        exclude_dynamic: bool,
        max_points: int,
    ) -> tuple[dict[str, Any], int]:
        """Return a bounded-cache WebGL payload for responsive replay and scrubbing."""
        key = (
            int(frame_id),
            int(pixel_stride),
            round(float(max_depth), 4),
            bool(exclude_dynamic),
            int(max_points),
        )
        cached = self.cloud_cache.pop(key, None)
        if cached is not None:
            self.cloud_cache[key] = cached
            return cached
        points, colors, raw_count = self.point_cloud(
            frame_id, pixel_stride, max_depth, exclude_dynamic, max_points
        )
        result = (viewer._encode_cloud(points, colors, self.center, self.scale), raw_count)
        self.cloud_cache[key] = result
        while len(self.cloud_cache) > self.cloud_cache_size:
            self.cloud_cache.popitem(last=False)
        return result

    def depth(self, frame_id: int, side: str) -> tuple[np.ndarray, bool]:
        """Load depth; return ``(depth, is_reprojected)``."""
        key = (side, frame_id)
        cached = self.depth_cache.pop(key, None)
        if cached is not None:
            self.depth_cache[key] = cached
            return cached.copy(), side == "right" and self.artifacts.right_depth_dir is None

        if side == "left":
            path = self.artifacts.left_depth_dir / f"{frame_id:06d}.npy"
            depth = np.asarray(np.load(path), dtype=np.float32)
            reprojected = False
        elif self.artifacts.right_depth_dir is not None:
            path = self.artifacts.right_depth_dir / f"{frame_id:06d}.npy"
            depth = np.asarray(np.load(path), dtype=np.float32)
            reprojected = False
        else:
            left, _ = self.depth(frame_id, "left")
            depth, _ = self.reproject_left_to_right(left)
            reprojected = True

        self.depth_cache[key] = depth
        while len(self.depth_cache) > self.depth_cache_size:
            self.depth_cache.popitem(last=False)
        return depth.copy(), reprojected

    def masks(self, frame_id: int) -> tuple[np.ndarray, np.ndarray, bool]:
        height = self.left_reader.height
        left = self.left_masks.frame(frame_id, height)
        if self.right_masks is not None:
            return left, self.right_masks.frame(frame_id, height), False
        left_depth, _ = self.depth(frame_id, "left")
        _, right = self.reproject_left_to_right(left_depth, left)
        # One-pixel dilation closes rasterization gaps without changing source masks.
        right = cv2.dilate(right.astype(np.uint8), np.ones((3, 3), np.uint8)) > 0
        return left, right, True

    def reproject_left_to_right(
        self, depth: np.ndarray, mask: np.ndarray | None = None
    ) -> tuple[np.ndarray, np.ndarray]:
        """Z-buffer rectified left pixels into the right image plane."""
        height, width = depth.shape
        y, x = np.indices((height, width), dtype=np.int32)
        valid = (
            np.isfinite(depth)
            & (depth > 1e-6)
            & self.left_valid
        )
        disparity = np.zeros_like(depth, dtype=np.float32)
        disparity[valid] = float(self.K[0, 0] * self.baseline_m) / depth[valid]
        right_x = np.rint(x.astype(np.float32) - disparity).astype(np.int32)
        valid &= (right_x >= 0) & (right_x < width)
        valid &= self.right_valid[y, np.clip(right_x, 0, width - 1)]

        target = y[valid] * width + right_x[valid]
        values = depth[valid]
        right_depth_flat = np.full(height * width, np.inf, dtype=np.float32)
        np.minimum.at(right_depth_flat, target, values)
        right_depth = right_depth_flat.reshape(height, width)
        right_depth[~np.isfinite(right_depth)] = 0.0

        right_mask_flat = np.zeros(height * width, dtype=np.uint8)
        if mask is not None:
            mask_values = mask[valid].astype(np.uint8)
            np.maximum.at(right_mask_flat, target, mask_values)
        return right_depth, right_mask_flat.reshape(height, width).astype(bool)

    def point_cloud(
        self,
        frame_id: int,
        pixel_stride: int,
        max_depth: float,
        exclude_dynamic: bool,
        max_points: int,
    ) -> tuple[np.ndarray, np.ndarray, int]:
        """Backproject the left metric depth and transform it to VIPE world space."""
        rgb = self.left_reader.read(frame_id)
        depth, _ = self.depth(frame_id, "left")
        mask = self.left_masks.frame(frame_id, self.left_reader.height)
        stride = max(1, int(pixel_stride))
        yy, xx = np.mgrid[0 : depth.shape[0] : stride, 0 : depth.shape[1] : stride]
        z = depth[::stride, ::stride]
        valid = (
            np.isfinite(z)
            & (z > 1e-6)
            & (z <= float(max_depth))
            & self.left_valid[::stride, ::stride]
        )
        if exclude_dynamic:
            valid &= ~mask[::stride, ::stride]
        x = (xx.astype(np.float32) - float(self.K[0, 2])) * z / float(self.K[0, 0])
        y = (yy.astype(np.float32) - float(self.K[1, 2])) * z / float(self.K[1, 1])
        camera_points = np.stack((x[valid], y[valid], z[valid]), axis=1)
        colors = rgb[::stride, ::stride][valid]
        pose = self.pose(frame_id)
        world = camera_points @ pose[:3, :3].T + pose[:3, 3]
        raw_count = len(world)
        maximum = max(1_000, int(max_points))
        if raw_count > maximum:
            indices = np.linspace(0, raw_count - 1, maximum, dtype=np.int64)
            world = world[indices]
            colors = colors[indices]
        return world.astype(np.float32), colors.astype(np.uint8), raw_count

    def _estimate_world_normalization(self) -> tuple[np.ndarray, float, float]:
        """Estimate stable viewer bounds from sparse frames without loading the sequence."""
        samples: list[np.ndarray] = []
        frame_count = max(1, min(self.left_reader.frame_count, 313))
        for frame_id in np.linspace(0, frame_count - 1, min(9, frame_count), dtype=int):
            path = self.artifacts.left_depth_dir / f"{frame_id:06d}.npy"
            if not path.is_file():
                continue
            depth = np.asarray(np.load(path, mmap_mode="r"), dtype=np.float32)
            stride = 24
            yy, xx = np.mgrid[0 : depth.shape[0] : stride, 0 : depth.shape[1] : stride]
            z = depth[::stride, ::stride]
            valid = np.isfinite(z) & (z > 0.1) & (z < 5.0)
            x = (xx - self.K[0, 2]) * z / self.K[0, 0]
            y = (yy - self.K[1, 2]) * z / self.K[1, 1]
            points = np.stack((x[valid], y[valid], z[valid]), axis=1)
            pose = self.pose(int(frame_id))
            samples.append(points @ pose[:3, :3].T + pose[:3, 3])
        if not samples:
            return np.zeros(3, dtype=np.float32), 1.0, 2.0
        points = np.concatenate(samples, axis=0)
        low, high = np.percentile(points, [1.0, 99.0], axis=0)
        center = ((low + high) * 0.5).astype(np.float32)
        extent = max(float(np.max(high - low)), 1e-3)
        return center, 2.0 / extent, extent


